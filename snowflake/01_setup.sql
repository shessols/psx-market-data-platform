-- Run once in a Snowflake worksheet.
CREATE DATABASE IF NOT EXISTS PSX;
CREATE SCHEMA IF NOT EXISTS PSX.RAW;
CREATE SCHEMA IF NOT EXISTS PSX.MART;   -- dbt builds its models here

CREATE TABLE IF NOT EXISTS PSX.RAW.DAILY_PRICES (
    SYMBOL     VARCHAR(20)   NOT NULL,
    DATE       DATE          NOT NULL,
    OPEN       NUMBER(18,4),
    HIGH       NUMBER(18,4),
    LOW        NUMBER(18,4),
    CLOSE      NUMBER(18,4),
    VOLUME     NUMBER(20,0),
    LOADED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (SYMBOL, DATE)
);

CREATE TABLE IF NOT EXISTS PSX.RAW.STOCKS (
    SYMBOL     VARCHAR(20)   NOT NULL PRIMARY KEY,
    NAME       VARCHAR(200),
    SECTOR     VARCHAR(100),
    LOADED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
